#!/usr/bin/env python3
"""Regenerates THIRD-PARTY-NOTICES.md from Cargo's dependency graph (browser build) plus the
vendored JavaScript, and fails if any dependency is not permissively licensed.

    python3 scripts/third-party-notices.py          # rewrite the file
    python3 scripts/third-party-notices.py --check  # CI: fail if the file is out of date
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
COPYLEFT = ("GPL", "AGPL", "LGPL", "SSPL", "EUPL")

# Vendored browser code (web/vendor/). Keep in sync when vendoring something new.
VENDORED = [
    ("three.js", "0.186.1", "MIT", "https://github.com/mrdoob/three.js", "web/vendor/three/LICENSE"),
    ("Anthropic TypeScript SDK", "0.129.0", "MIT", "https://github.com/anthropics/anthropic-sdk-typescript", "web/vendor/anthropic/LICENSE"),
    ("@stablelib/base64 (bundled in the SDK file)", "1.0.1", "MIT", "https://github.com/StableLib/stablelib", "web/vendor/anthropic/LICENSE-bundled.txt"),
    ("fast-sha256 (bundled in the SDK file)", "1.3.0", "Unlicense", "https://github.com/dchest/fast-sha256-js", "web/vendor/anthropic/LICENSE-bundled.txt"),
    ("standardwebhooks (bundled in the SDK file)", "1.1.1", "MIT", "https://github.com/standard-webhooks/standard-webhooks", "web/vendor/anthropic/LICENSE-bundled.txt"),
]


def cargo_packages():
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked",
             "--filter-platform", "wasm32-unknown-unknown"],
            cwd=ROOT,
        )
    )
    members = set(meta["workspace_members"])
    used = {node["id"] for node in meta["resolve"]["nodes"]}
    return sorted(
        (p for p in meta["packages"] if p["id"] in used and p["id"] not in members),
        key=lambda p: p["name"],
    )


def render(packages):
    lines = [
        "# Third-party notices",
        "",
        "EasyCAD is private (all rights reserved). It includes the open-source components below,",
        "each under its own permissive license. Generated by `scripts/third-party-notices.py`;",
        "do not edit by hand.",
        "",
        "## Rust crates (compiled into the engine)",
        "",
        "| Crate | Version | License | Source |",
        "|---|---|---|---|",
    ]
    for p in packages:
        repo = p.get("repository") or p.get("homepage") or ""
        lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see source'} | {repo} |")
    lines += ["", "## Vendored JavaScript", "", "| Library | Version | License | Source | License file |", "|---|---|---|---|---|"]
    for name, version, lic, url, path in VENDORED:
        lines.append(f"| {name} | {version} | {lic} | {url} | `{path}` |")
    lines.append("")
    return "\n".join(lines)


def main():
    packages = cargo_packages()
    bad = [p for p in packages if any(c in (p.get("license") or "") and "OR" not in (p.get("license") or "")
                                       for c in COPYLEFT)]
    if bad:
        for p in bad:
            print(f"not permissive: {p['name']} {p['version']} ({p['license']})", file=sys.stderr)
        sys.exit(1)
    text = render(packages)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("THIRD-PARTY-NOTICES.md is out of date: run scripts/third-party-notices.py", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT.name}: {len(packages)} crates, {len(VENDORED)} vendored libraries")


if __name__ == "__main__":
    main()
